def tab_es():
    f, g = os.path.join(TABLE_DIR, "es", "T4.1_es_tests.csv"), os.path.join(TABLE_DIR, "es", "T4.2_es_mcs.csv")
    if not (os.path.exists(f) and os.path.exists(g)):
        return
    t = pd.read_csv(f).merge(pd.read_csv(g)[["series", "period", "alpha", "model", "MCS_p", "in_MCS_90"]],
                             on=["series", "period", "alpha", "model"])
    s = t[t.period == "all"]
    rows, last = [], None
    for _, r in s.iterrows():
        key = (r.series, r.alpha)
        if last is not None and key != last:
            rows.append("MIDRULE")
        last = key
        mcs = fmcs(r.MCS_p, r.in_MCS_90)
        rows.append([r.series, pct(r.alpha), LAB[r.model], f"{int(r.hits)}", fn(r.avg_ES), fn(r.avg_loss_beyond_VaR),
                     fn(r.avg_ES_on_hit_days), fp(r.MF_p), fp(r.UES_p), fp(r.CES5_p), fn(r.FZ0, 3),
                     fdm(r.get("DM_FZ0_vs_HS"), r.get("DM_FZ0_p")), mcs])
    write("tab_es", "lllrrrrrrrrrr",
          r"Series & $\alpha$ & Model & Hits & ES & Loss$|$hit & ES$|$hit & MF & U$_{ES}$ & C$_{ES}$ & FZ0 & DM & MCS", rows,
          "Expected Shortfall: backtests, FZ0 loss and Model Confidence Set, 1/10/2021--30/09/2026.", "tab:es",
          note=r"ES: average ES (\%). Loss$|$hit, ES$|$hit: average return and average ES on violation days. MF: McNeil-Frey "
               r"(one-sided, bootstrap); U$_{ES}$, C$_{ES}$: Du-Escanciano unconditional and conditional tests; p-values in "
               r"bold: rejection at 5\%. FZ0: average loss of Patton, Ziegel and Chen (2019). DM: against HS on FZ0. "
               r"MCS on FZ0, $^\dagger$ = in the 90\% MCS.", size=r"\scriptsize")
    # FZ0 by calendar year
    y = t[t.period != "all"]
    years = sorted(y.period.unique())
    rows, last = [], None
    for (se, a, m), gg in y.groupby(["series", "alpha", "model"], sort=False):
        if last is not None and (se, a) != last:
            rows.append("MIDRULE")
        last = (se, a)
        v = gg.set_index("period")
        rows.append([se, pct(a), LAB[m], *[(fn(v.loc[p, "FZ0"], 3) + (r"$^\dagger$" if v.loc[p, "in_MCS_90"] else "")) for p in years]])
    write("tab_es_years", "lll" + "r" * len(years), r"Series & $\alpha$ & Model & " + " & ".join(years), rows,
          r"Expected Shortfall by calendar year: average FZ0 loss ($^\dagger$ = in the 90\% MCS of that year).", "tab:es_years")


