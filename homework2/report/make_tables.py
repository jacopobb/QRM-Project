# ------------------------------------------------------------------ formatting helpers
def fp(p):
    """p-value: 3 decimals, bold when below SIG, '--' when missing."""
    if pd.isna(p):
        return "--"
    s = "$<$0.001" if p < 0.001 else f"{p:.3f}"
    return rf"\textbf{{{s}}}" if p < SIG else s


def fn(x, d=2):
    """Number with d decimals, '--' when missing."""
    return "--" if pd.isna(x) else f"{x:.{d}f}"


def fmcs(p, inside):
    """MCS p-value (not in bold: the MCS uses its own 10% level), dagger when the model is in the 90% MCS."""
    return "--" if pd.isna(p) else f"{p:.3f}" + (r"$^\dagger$" if inside else "")


def fdm(s, p):
    """Diebold-Mariano statistic with a star when significant at 5% (negative = better than the benchmark)."""
    return "--" if pd.isna(s) else f"{s:.2f}" + ("$^{*}$" if p < SIG else "")


def write(name, colspec, header, rows, caption, label, note="", size=r"\footnotesize", group_after=None):
    """Writes a complete table environment to report/tables/<name>.tex."""
    os.makedirs(OUT, exist_ok=True)
    lines = [r"\begin{table}[htbp]", r"\centering", size, rf"\caption{{{caption}}}", rf"\label{{{label}}}",
             r"\begin{adjustbox}{max width=\linewidth}",           # shrink only the tables wider than the text
             rf"\begin{{tabular}}{{{colspec}}}", r"\toprule", header + r" \\", r"\midrule"]
    for i, r in enumerate(rows):
        if r == "MIDRULE":                                   # separator between panels
            lines.append(r"\midrule")
            continue
        lines.append(" & ".join(r) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{adjustbox}"]
    if note:
        lines.append(rf"\par\smallskip\parbox{{0.95\linewidth}}{{\scriptsize {note}}}")
    lines.append(r"\end{table}")
    with open(os.path.join(OUT, f"{name}.tex"), "w", encoding="utf-8") as f:
        f.write("% generated by report/make_tables.py - do not edit by hand\n" + "\n".join(lines) + "\n")


def pct(a):
    return f"{int(round(a * 100))}\\%"


