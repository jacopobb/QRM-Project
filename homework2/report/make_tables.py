# ------------------------------------------------------------------ Point 2: backtesting
def tab_bt_full(series):
    f = os.path.join(BT, f"T2.1_full_{series}.csv")
    if not os.path.exists(f):
        return
    t = pd.read_csv(f, index_col=0)
    for a in ALPHAS:
        s = t[t.alpha == a]
        rows = [[LAB[m], f"{int(r.hits)}", fn(100 * r.hit_rate), fp(r.UC_p), fp(r.IND_p), fp(r.CC_p), fp(r.BCP_p),
                 fp(r.DQ_p), fdm(r.get("DM_tick"), r.get("DM_tick_p")), fdm(r.get("DM_lopez"), r.get("DM_lopez_p")),
                 fmcs(r.MCS_p, r.in_MCS)] for m, r in s.iterrows()]
        write(f"tab_bt_{series}_{a}", "lrrrrrrrrrr",
              r"Model & Hits & Rate \% & UC & IND & CC & BCP & DQ & DM tick & DM Lopez & MCS", rows,
              f"Backtesting of the {pct(a)} VaR, {series}, 1/10/2021--30/09/2026 ({int(s.n.iloc[0])} days).",
              f"tab:bt_{series}_{a}",
              note=r"UC, IND, CC: Kupiec and Christoffersen; BCP: Ljung-Box(5) on the hits (Berkowitz, Christoffersen "
                   r"and Pelletier, 2011); DQ: Engle-Manganelli. p-values in bold: rejection at 5\%. DM: Diebold-Mariano "
                   r"statistic against HS (negative = lower loss than HS, $^{*}$ significant at 5\%). MCS: p-value of the "
                   r"Model Confidence Set on the tick loss, $^\dagger$ = in the 90\% MCS.")


